// Command lolbas generates rules/lolbas.yaml from the LOLBAS project's catalog of living-off-
// the-land binaries (https://lolbas-project.github.io, GPL-3.0).
//
//	go run ./tools/lolbas                       download the catalog and write rules/lolbas.yaml
//	go run ./tools/lolbas -in lolbas.json       from a saved copy of the API JSON
//
// Each LOLBAS example command becomes a ProcessCreated rule: the image must be the binary, and
// the command line must contain the command's distinctive tokens (flags, verbs, DLL names and
// entry points). Placeholders ({REMOTEURL}, {PATH}, ...), paths, file names and numbers vary
// between uses and are left out. A command with nothing distinctive left (only "binary plus a
// file") is skipped: it would fire on every ordinary run of the binary.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

const catalogURL = "https://lolbas-project.github.io/api/lolbas.json"

type binary struct {
	Name     string    `json:"Name"`
	Commands []command `json:"Commands"`
}

type command struct {
	Command     string `json:"Command"`
	Description string `json:"Description"`
	Usecase     string `json:"Usecase"`
	Category    string `json:"Category"`
	MitreID     string `json:"MitreID"`
}

// rule is written in the same shape as the hand-written rule files
type rule struct {
	Name        string   `yaml:"name"`
	Description string   `yaml:"description"`
	Severity    string   `yaml:"severity"`
	Action      string   `yaml:"action"`
	Sequence    []string `yaml:"sequence"`

	tokens []string // for -list
}

func main() {
	in := flag.String("in", "", "LOLBAS API JSON file (default: download "+catalogURL+")")
	out := flag.String("out", "rules/lolbas.yaml", "rule file to write")
	list := flag.Bool("list", false, "print each rule's binary and tokens instead of writing the file (for review)")
	flag.Parse()

	data, err := readCatalog(*in)
	if err != nil {
		log.Fatal(err)
	}
	var catalog []binary
	if err := json.Unmarshal(data, &catalog); err != nil {
		log.Fatalf("parsing the catalog: %v", err)
	}

	rs, stats := generate(catalog)
	if *list {
		for _, r := range rs {
			fmt.Printf("%-28s %-8s %s\n", r.Name, r.Severity, r.tokens)
		}
		return
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# GENERATED by tools/lolbas from the LOLBAS project (%s). Do not edit by hand;
# regenerate with: go run ./tools/lolbas
#
# LOLBAS (https://github.com/LOLBAS-Project/LOLBAS) is licensed under GPL-3.0; these rules are
# derived from its catalog.
#
# One rule per distinct (binary, tokens) pair: the process image is the binary and the command
# line has every token at a word boundary. Flags match with - or /. All rules alert only.
#
# %d binaries, %d commands: %d rules. Skipped: %d commands with nothing distinctive besides the
# binary and its file arguments, %d too generic for a binary in everyday use (fewer than %d
# tokens), %d that run a script or another file a rule cannot name.
`, catalogURL, stats.binaries, stats.commands, len(rs), stats.noTokens, stats.common, minCommonTokens, stats.notExe)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(rs); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d rules to %s (skipped: %d without distinctive tokens, %d too generic, %d not an .exe or .dll)",
		len(rs), *out, stats.noTokens, stats.common, stats.notExe)
}

func readCatalog(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	resp, err := http.Get(catalogURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", catalogURL, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

type stats struct{ binaries, commands, noTokens, notExe, common int }

// Binaries that developers, installers and Windows itself run all day. Their rules need at
// least minCommonTokens tokens, so "cmd /c", "msiexec /quiet /i" or "csc -out" do not alert on
// every build or install
var commonBinaries = map[string]bool{
	"cmd.exe": true, "powershell.exe": true, "pwsh.exe": true, "bash.exe": true, "wsl.exe": true,
	"msiexec.exe": true, "regsvr32.exe": true, "rundll32.exe": true, "explorer.exe": true,
	"mmc.exe": true, "conhost.exe": true, "msedge.exe": true, "msedgewebview2.exe": true,
	"teams.exe": true, "schtasks.exe": true, "sc.exe": true, "reg.exe": true, "tar.exe": true,
	"ssh.exe": true, "scp.exe": true, "sftp.exe": true, "csc.exe": true, "vbc.exe": true,
	"jsc.exe": true, "ilasm.exe": true, "msbuild.exe": true, "dotnet.exe": true, "winget.exe": true,
	"cipher.exe": true, "query.exe": true, "change.exe": true, "makecab.exe": true,
	"replace.exe": true, "print.exe": true, "findstr.exe": true, "pktmon.exe": true,
	"cscript.exe": true, "wscript.exe": true, "tracker.exe": true, "esentutl.exe": true,
}

const minCommonTokens = 3

// DLL entry points Windows and common apps call through rundll32 all the time (Control Panel
// applets, opening links)
var benignDllCalls = map[string]bool{
	"shell32.dll control_rundll": true, "shell32.dll shellexec_rundll": true,
	"url.dll fileprotocolhandler": true, "url.dll openurl": true,
}

// distinctive reports whether the tokens are specific enough for a binary in everyday use:
// minCommonTokens of them, or a named DLL with its entry point (rundll32 advpack.dll,LaunchINFSection)
func distinctive(toks []string) bool {
	if len(toks) >= minCommonTokens {
		return true
	}
	if len(toks) == 2 && dllRE.MatchString(toks[0]) && !benignDllCalls[toks[0]+" "+toks[1]] {
		return true
	}
	return false
}

// Command separators: a LOLBAS example may set up with other commands first
var separators = map[string]bool{"&&": true, "&": true, "||": true, "|": true, ">": true, ">>": true, "<": true}

// binaryIndex finds the field that runs the binary (by file name, with or without .exe)
func binaryIndex(fields []string, name string) int {
	stem := strings.TrimSuffix(name, ".exe")
	for i, f := range fields {
		f = strings.ToLower(f)
		if j := strings.LastIndexAny(f, `\/`); j >= 0 {
			f = f[j+1:]
		}
		f = strings.TrimRight(f, "<>|&;")
		if f == name || f == stem {
			return i
		}
	}
	return -1
}

// arguments returns the fields up to the next command separator
func arguments(fields []string) []string {
	for i, f := range fields {
		if separators[f] || strings.HasPrefix(f, ">") || strings.HasPrefix(f, "|") {
			return fields[:i]
		}
	}
	return fields
}

// target returns the process the command starts and its arguments. LOLBAS .exe entries are
// found by name in the command; DLL entries run under the host the command starts with
// (rundll32, regsvr32) and must name the DLL. Scripts and other files are not supported
func target(bin binary, c command) (exe string, args []string, ok bool) {
	name := strings.ToLower(bin.Name)
	fields := splitCommand(c.Command)
	switch {
	case strings.HasSuffix(name, ".exe"):
		i := binaryIndex(fields, name)
		if i < 0 {
			return "", nil, false
		}
		return name, arguments(fields[i+1:]), true
	case strings.HasSuffix(name, ".dll") && len(fields) > 1:
		host, ok := executable(fields[0])
		if !ok || binaryIndex(arguments(fields[1:]), name) < 0 &&
			!strings.Contains(strings.ToLower(c.Command), name) {
			return "", nil, false
		}
		return host, arguments(fields[1:]), true
	}
	return "", nil, false
}

func generate(catalog []binary) ([]rule, stats) {
	var st stats
	var out []rule
	seen := map[string]bool{}  // exe + tokens, to merge commands that reduce to the same rule
	perExe := map[string]int{} // rule numbering per binary

	sort.Slice(catalog, func(i, j int) bool { return strings.ToLower(catalog[i].Name) < strings.ToLower(catalog[j].Name) })
	for _, bin := range catalog {
		st.binaries++
		for _, c := range bin.Commands {
			st.commands++
			exe, args, ok := target(bin, c)
			if !ok {
				st.notExe++
				continue
			}
			toks := tokens(args)
			if len(toks) == 0 {
				st.noTokens++
				continue
			}
			if commonBinaries[exe] && !distinctive(toks) {
				st.common++
				continue
			}
			key := exe + "\x00" + strings.Join(toks, "\x00")
			if seen[key] {
				continue
			}
			seen[key] = true

			stem := regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(strings.TrimSuffix(exe, ".exe"), "_")
			perExe[stem]++
			name := fmt.Sprintf("lolbas_%s_%d", stem, perExe[stem])

			cond := []string{
				`Event == "ProcessCreated"`,
				`lower(Image) endsWith ` + strconv.Quote(`\`+exe),
			}
			for _, t := range toks {
				cond = append(cond, `lower(CommandLine) matches `+strconv.Quote(tokenPattern(t)))
			}
			out = append(out, rule{
				Name:        name,
				Description: describe(bin.Name, c),
				Severity:    severity(c.Category),
				Action:      "alert",
				Sequence:    []string{strings.Join(cond, " && ")},
				tokens:      append([]string{exe}, toks...),
			})
		}
	}
	return out, st
}

func describe(bin string, c command) string {
	d := fmt.Sprintf("LOLBAS %s (%s", bin, c.Category)
	if c.MitreID != "" {
		d += ", " + c.MitreID
	}
	d += "): " + strings.TrimSpace(c.Usecase)
	return strings.Join(strings.Fields(d), " ")
}

// Credential theft and memory dumps are the most direct harm; execution and file tricks are
// common in benign admin work too
func severity(category string) string {
	switch category {
	case "Credentials", "Dump":
		return "high"
	case "Download", "Upload", "AWL Bypass", "UAC Bypass", "Tamper", "Conceal":
		return "medium"
	}
	return "low"
}

// splitCommand splits on whitespace outside double quotes and removes the quotes
func splitCommand(s string) []string {
	var out []string
	var cur strings.Builder
	inQuote := false
	for _, r := range s {
		switch {
		case r == '"':
			inQuote = !inQuote
		case (r == ' ' || r == '\t') && !inQuote:
			if cur.Len() > 0 {
				out = append(out, cur.String())
				cur.Reset()
			}
		default:
			cur.WriteRune(r)
		}
	}
	if cur.Len() > 0 {
		out = append(out, cur.String())
	}
	return out
}

// executable returns the lowercased file name of the binary a command runs. Commands that start
// with a script or other non-.exe file are run by a host process the rule cannot name
func executable(first string) (string, bool) {
	name := strings.ToLower(first)
	if i := strings.LastIndexAny(name, `\/`); i >= 0 {
		name = name[i+1:]
	}
	if strings.ContainsAny(name, "{}") || name == "" {
		return "", false
	}
	if !strings.Contains(name, ".") {
		name += ".exe"
	}
	return name, strings.HasSuffix(name, ".exe")
}

var (
	wordRE   = regexp.MustCompile(`^[a-z][a-z0-9_-]*$`)
	dllRE    = regexp.MustCompile(`^[a-z0-9_-]+\.dll$`)
	schemeRE = regexp.MustCompile(`^(javascript|vbscript|script|mshtml|about):`)
	flagRE   = regexp.MustCompile(`^(--|//|-|/)[a-z0-9?][a-z0-9_.?-]*$`)
)

// Words in the examples that stand for arbitrary values rather than syntax
var placeholderWords = map[string]bool{
	"anythinghere": true, "localhost": true, "test": true, "foo": true, "bar": true, "foobar": true,
	"null": true, "or": true, "java": true, "lolbin": true, "mytask": true, "targetmachine": true,
}

// Parts of example names (evilservice, dummy_assembly_name, your_id, lolbas-project, ...)
var placeholderParts = []string{"evil", "malware", "dummy", "your_", "example", "lolbas", "export_name", "w3all", "payload"}

// isPlaceholder reports whether a word in an example command stands for an arbitrary value
func isPlaceholder(w string) bool {
	if len(w) <= 1 || placeholderWords[w] {
		return true
	}
	for _, p := range placeholderParts {
		if strings.Contains(w, p) {
			return true
		}
	}
	return false
}

// tokens reduces the arguments of a command to what identifies the technique
func tokens(args []string) []string {
	var out []string
	add := func(t string) {
		for _, have := range out {
			if have == t {
				return
			}
		}
		out = append(out, t)
	}
	for _, arg := range args {
		a := strings.ToLower(arg)
		// Keep what precedes a placeholder: "/i:{REMOTEURL}" -> "/i:"
		if i := strings.Index(a, "{"); i >= 0 {
			a = a[:i]
		}
		if a == "" {
			continue
		}
		if m := schemeRE.FindString(a); m != "" {
			add(m) // javascript:..., script:...
			continue
		}
		if a[0] == '-' || (a[0] == '/' && !strings.HasPrefix(a, "//") || strings.HasPrefix(a, "//")) {
			// A flag: cut its value off ("/i:x", "--path=x", "/root,x")
			if i := strings.IndexAny(a, ":=,"); i > 0 {
				a = a[:i]
			}
			if flagRE.MatchString(a) && strings.IndexFunc(a, isLetter) >= 0 {
				add(a)
			}
			continue
		}
		for _, part := range strings.Split(a, ",") {
			if i := strings.LastIndexAny(part, `\/`); i >= 0 {
				part = part[i+1:] // a path: only its file name can matter
			}
			switch {
			case dllRE.MatchString(part) && !isPlaceholder(strings.TrimSuffix(part, ".dll")):
				add(part)
			case wordRE.MatchString(part) && !isPlaceholder(part) && !strings.Contains(arg, `\`):
				add(part)
			}
		}
	}
	return out
}

func isLetter(r rune) bool { return r >= 'a' && r <= 'z' }

// tokenPattern matches a token as a whole word in a lowercased command line. A single - or /
// flag matches with either, since most Windows tools accept both
func tokenPattern(t string) string {
	const before, after = `(^|[\s"',\\])`, `([\s"':=,]|$)`
	switch {
	case strings.HasSuffix(t, ":") && schemeRE.MatchString(t):
		return before + regexp.QuoteMeta(t)
	case strings.HasPrefix(t, "--"), strings.HasPrefix(t, "//"):
		return before + regexp.QuoteMeta(t) + after
	case t[0] == '-' || t[0] == '/':
		return before + `[-/]` + regexp.QuoteMeta(t[1:]) + after
	}
	return before + regexp.QuoteMeta(t) + after
}
