// sealmodel encrypts model.onnx so it can be embedded in PanoptesML.dll, and writes the key as a
// C++ header for the DLL to decrypt it with. The build runs it (CMakeLists.txt); it isn't
// needed by hand:
//
//	go run ./sealmodel -in model.onnx -out model.sealed -header model_key.h
//
// The model is encrypted with AES-256-GCM under a new random key each time. The DLL decrypts it
// in memory and hands it to ONNX Runtime, so no plain model.onnx is shipped, and a modified
// model fails its GCM check instead of loading.
//
// This hides the model; it doesn't secure it. The key ships inside the DLL (split into two
// masked halves, so it isn't one searchable run of bytes), so anyone who reverse-engineers the
// DLL, or reads its memory while it runs, can recover the model.
//
// Sealed format, read by src/model_seal.cpp:
//
//	magic "PMLE" | version uint32 LE (1) | nonce [12] | ciphertext | GCM tag [16]
//
// The magic and version (the first 8 bytes) are the GCM additional data.
package main

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/binary"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
)

const (
	magic     = "PMLE"
	version   = 1
	keySize   = 32
	nonceSize = 12
	tagSize   = 16
)

func main() {
	in := flag.String("in", "", "model.onnx to seal")
	out := flag.String("out", "", "sealed model to write (embedded in the DLL as a resource)")
	header := flag.String("header", "", "C++ header to write the key to")
	flag.Parse()
	if *in == "" || *out == "" || *header == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*in, *out, *header); err != nil {
		log.Fatal(err)
	}
}

func run(in, out, header string) error {
	model, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	if len(model) == 0 {
		return fmt.Errorf("%s is empty", in)
	}
	key := make([]byte, keySize)
	if _, err := rand.Read(key); err != nil {
		return err
	}
	sealed, err := seal(model, key)
	if err != nil {
		return err
	}
	mask := make([]byte, keySize)
	if _, err := rand.Read(mask); err != nil {
		return err
	}
	if err := os.WriteFile(out, sealed, 0o644); err != nil {
		return err
	}
	return os.WriteFile(header, []byte(keyHeader(key, mask)), 0o644)
}

func seal(model, key []byte) ([]byte, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return nil, err
	}
	b := make([]byte, 8, 8+nonceSize+len(model)+tagSize)
	copy(b, magic)
	binary.LittleEndian.PutUint32(b[4:], version)
	nonce := make([]byte, nonceSize)
	if _, err := rand.Read(nonce); err != nil {
		return nil, err
	}
	b = append(b, nonce...)
	return gcm.Seal(b, nonce, model, b[:8]), nil
}

// open reverses seal (the DLL's job; here for the tests)
func open(sealed, key []byte) ([]byte, error) {
	if len(sealed) < 8+nonceSize+tagSize || string(sealed[:4]) != magic || binary.LittleEndian.Uint32(sealed[4:]) != version {
		return nil, errors.New("not a sealed model")
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return nil, err
	}
	return gcm.Open(nil, sealed[8:8+nonceSize], sealed[8+nonceSize:], sealed[:8])
}

// keyHeader writes the key as two arrays whose XOR is the key, so it isn't one searchable run
// of bytes in the DLL
func keyHeader(key, mask []byte) string {
	hexList := func(b []byte) string {
		parts := make([]string, len(b))
		for i, v := range b {
			parts[i] = fmt.Sprintf("0x%02x", v)
		}
		return strings.Join(parts, ", ")
	}
	masked := make([]byte, len(key))
	for i := range key {
		masked[i] = key[i] ^ mask[i]
	}
	return fmt.Sprintf(`// Generated by tools/sealmodel when the model is sealed. Do not edit or commit.
#pragma once
// The model key is g_ModelKeyMasked XOR g_ModelKeyMask. Not const, so the compiler can't fold
// the two into the key itself
static unsigned char g_ModelKeyMasked[%d] = { %s };
static unsigned char g_ModelKeyMask[%d] = { %s };
`, keySize, hexList(masked), keySize, hexList(mask))
}
